"""Write hash-locked requirement files for CI, using only pip and the standard library.

CI installs with ``pip install --require-hashes``, which needs every package,
transitive ones included, pinned to one version with its hashes. This script
asks pip which versions it would install for CI's platform (Linux x86_64,
CPython 3.12), then records the sha256 of every file PyPI publishes for each
of those versions, so the lock holds whichever wheel or sdist pip picks.

Run it from the repo root after changing requirements.txt or
requirements-dev.txt, with any Python 3.11+ that has pip:

    python scripts/lock_requirements.py

It writes requirements.lock (runtime) and requirements-dev.lock (runtime and
test). Commit both with the change that needed them.
"""

import json
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

PLATFORMS = ["manylinux_2_17_x86_64", "manylinux2014_x86_64", "manylinux_2_28_x86_64", "linux_x86_64"]
PYTHON_VERSION = "3.12"
LOCKS = {
    "requirements.lock": ["requirements.txt"],
    "requirements-dev.lock": ["requirements.txt", "requirements-dev.txt"],
}


def resolve(inputs: list[str]) -> list[tuple[str, str]]:
    """Return the (name, version) pairs pip would install for CI's platform from these requirement files."""
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        args = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
                "--report", str(report), "--python-version", PYTHON_VERSION, "--implementation", "cp",
                "--only-binary=:all:"]
        for platform in PLATFORMS:
            args += ["--platform", platform]
        for path in inputs:
            args += ["-r", path]
        subprocess.run(args, check=True)
        installs = json.loads(report.read_text(encoding="utf-8"))["install"]
    return sorted({(i["metadata"]["name"], i["metadata"]["version"]) for i in installs}, key=lambda p: p[0].lower())


def file_hashes(name: str, version: str) -> list[str]:
    """Return the sha256 of every file PyPI publishes for this exact release."""
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as response:
        release = json.load(response)
    hashes = sorted({f["digests"]["sha256"] for f in release["urls"]})
    if not hashes:
        raise SystemExit(f"PyPI lists no files for {name}=={version}")
    return hashes


def lock_text(inputs: list[str], pins: list[tuple[str, str]]) -> str:
    """Render a pip requirements file that pins each package with all of its hashes."""
    lines = [f"# Generated by scripts/lock_requirements.py from {' + '.join(inputs)}; don't edit by hand.",
             f"# Resolved for CPython {PYTHON_VERSION} on Linux x86_64 (CI). Install with --require-hashes."]
    for name, version in pins:
        lines.append(f"{name}=={version} \\")
        hashes = file_hashes(name, version)
        lines += [f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else "") for i, h in enumerate(hashes)]
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write every lock file in LOCKS."""
    for lock, inputs in LOCKS.items():
        Path(lock).write_text(lock_text(inputs, resolve(inputs)), encoding="utf-8", newline="\n")
        print(f"wrote {lock}")


if __name__ == "__main__":
    main()
